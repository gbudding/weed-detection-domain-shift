"""Make the LaTeX tables for the report from results/*.csv.

Writes to report/tables/ (each file is a complete table environment, \\input it in main.tex):
  data            images and boxes per split
  main_results    weed AP50 and AP50-95 on greenhouse test and field test, and the gap (mean +- std over seeds)
  comparisons     paired bootstrap differences: RT-DETR vs YOLO, each ablation vs its baseline (appendix)
  comparisons_key the key rows of comparisons, single column, without CIs (main text)
  errors          field error types at conf 0.25 per model (baseline, mean over seeds)
  audit           label audit of field background false positives (if results/label_audit/summary.csv exists)

Configs that have not been run yet are shown as a dash, so the tables can be made at any time.
Run src/analyze.py and src/error_analysis.py first.
"""

import argparse
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
MODELS = {"yolo11s": "YOLO11s", "rtdetr-l": "RT-DETR-l"}
SETTINGS = [((640, "default"), "baseline"), ((1024, "default"), "1024 px"),
            ((640, "off"), "HSV off"), ((640, "strong"), "HSV strong"), ((640, "hue"), "full hue")]
SPLITS = {"greenhouse_train": "Greenhouse train", "greenhouse_val": "Greenhouse val",
          "greenhouse_test": "Greenhouse test", "field_test": "Field test"}
DASH = "--"
# Rows of the short comparisons table in the main text.
KEY_MODEL_SETTINGS = ("baseline", "HSV strong")
KEY_ABLATIONS = (("1024 px", "baseline"), ("HSV strong", "baseline"), ("full hue", "HSV strong"))


def pm(mean, std):
    if pd.isna(mean):
        return DASH
    return f"{mean:.3f}" if pd.isna(std) else f"{mean:.3f} $\\pm$ {std:.3f}"


def write(out_dir, name, body):
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{name}.tex").write_text("% Generated by src/make_tables.py; do not edit by hand.\n" + body, encoding="utf-8")
    print(f"  {name}")


def table_data(results_dir, out_dir):
    s = pd.read_csv(results_dir / "splits_summary.csv").set_index("split")
    rows = [f"{label} & {int(s.loc[k, 'n_images'])} & {int(s.loc[k, 'n_weed'])} & {int(s.loc[k, 'n_crop'])} \\\\"
            for k, label in SPLITS.items()]
    write(out_dir, "data", rf"""\begin{{table}}[t]
\caption{{Images and labelled boxes per split. Greenhouse splits are grouped by planter (blocks of 12 consecutive image IDs); all field images are test data.}}
\label{{tab:data}}
\centering\small
\begin{{tabular}}{{lrrr}}
\toprule
Split & Images & Weed & Crop \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}
\end{{table}}
""")


def table_main(summary, epochs, out_dir):
    s = summary[summary["epochs"] == epochs].set_index(["model", "imgsz", "hsv", "metric", "target"])

    def cell(model, key, metric, target):
        k = (model, *key, metric, target)
        return pm(s.loc[k, "mean"], s.loc[k, "std_seeds"]) if k in s.index else DASH

    rows = []
    for model, model_label in MODELS.items():
        for k, (key, label) in enumerate(SETTINGS):
            name = f"\\multirow{{{len(SETTINGS)}}}{{*}}{{{model_label}}}" if k == 0 else ""
            cells = [cell(model, key, "weed_AP50", t) for t in ("greenhouse_test", "field_test", "gap")]
            cells.append(cell(model, key, "weed_AP50-95", "field_test"))
            rows.append(f"{name} & {label} & " + " & ".join(cells) + " \\\\")
        rows.append("\\midrule")
    write(out_dir, "main_results", rf"""\begin{{table*}}[t]
\caption{{Weed detection after training on greenhouse images: mean $\pm$ std over 3 seeds ({epochs} epochs). Gap = greenhouse $-$ field AP50 (lower is better).}}
\label{{tab:main}}
\centering\small
\begin{{tabular}}{{llcccc}}
\toprule
Model & Setting & Greenhouse AP50 & Field AP50 & Gap & Field AP50--95 \\
\midrule
{chr(10).join(rows[:-1])}
\bottomrule
\end{{tabular}}
\end{{table*}}
""")


def table_comparisons(comparisons, epochs, out_dir, metric="weed_AP50"):
    c = comparisons[comparisons["metric"] == metric]
    labels = {f"{m}/{i}/{h}/{epochs}": (m, lab) for m in MODELS for (i, h), lab in SETTINGS}
    order = [lab for _, lab in SETTINGS]

    def fmt_p(p):
        return DASH if pd.isna(p) else "$<$0.001" if p < 0.001 else f"{p:.3f}"

    groups = {"model": [], "ablation": []}
    key_rows = {"model": [], "ablation": []}
    for (a, b), g in c.groupby(["a", "b"], sort=False):
        if a not in labels or b not in labels:
            continue
        (ma, la), (mb, lb) = labels[a], labels[b]
        if ma != mb:
            kind, name, key = "model", f"{la}", (order.index(la),)
        else:
            vs = "" if lb == "baseline" else f" vs {lb}"
            kind, name, key = "ablation", f"{MODELS[ma]}: {la}{vs}", (list(MODELS).index(ma), order.index(la))
        g = g.set_index("target")
        if (kind == "model" and la in KEY_MODEL_SETTINGS) or (kind == "ablation" and (la, lb) in KEY_ABLATIONS):
            short = (f"RT-DETR $-$ YOLO: {la}" if kind == "model"
                     else name.replace("11s", "").replace("-l:", ":").replace("vs HSV strong", "vs strong"))
            f, gp = g.loc["field_test"], g.loc["gap"]
            key_rows[kind].append((key, f"{short} & {f['diff_a_minus_b']:+.3f} & {fmt_p(f['p_bootstrap'])} & "
                                        f"{fmt_p(f.get('p_welch_seeds'))} & {gp['diff_a_minus_b']:+.3f} & "
                                        f"{fmt_p(gp.get('p_welch_seeds'))} \\\\"))
        cells = []
        for t in ("field_test", "gap"):
            r = g.loc[t]
            cells.append(f"{r['diff_a_minus_b']:+.3f} & [{r['ci_low']:+.3f}, {r['ci_high']:+.3f}] & "
                         f"{fmt_p(r['p_bootstrap'])} & {fmt_p(r.get('p_welch_seeds'))}")
        groups[kind].append((key, f"{name} & " + " & ".join(cells) + " \\\\"))
    rows = [r for _, r in sorted(groups["model"])]
    if rows and groups["ablation"]:
        rows.append("\\midrule")
    rows += [r for _, r in sorted(groups["ablation"])]
    write(out_dir, "comparisons", rf"""\begin{{table*}}[t]
\caption{{Differences in weed AP50, mean over 3 seeds. Top: RT-DETR-l minus YOLO11s at the same setting. Bottom: setting minus the same model's baseline. 95\% CI and $p_\mathrm{{img}}$: paired bootstrap over test images (1000 resamples), which ignores seed variation; $p_\mathrm{{seed}}$: Welch $t$-test over the 3 per-seed values.}}
\label{{tab:comparisons}}
\centering\small\setlength{{\tabcolsep}}{{4pt}}
\begin{{tabular}}{{lcccccccc}}
\toprule
 & \multicolumn{{4}}{{c}}{{Field AP50}} & \multicolumn{{4}}{{c}}{{Gap}} \\
\cmidrule(lr){{2-5}}\cmidrule(lr){{6-9}}
Comparison & $\Delta$ & 95\% CI & $p_\mathrm{{img}}$ & $p_\mathrm{{seed}}$ & $\Delta$ & 95\% CI & $p_\mathrm{{img}}$ & $p_\mathrm{{seed}}$ \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}
\end{{table*}}
""")
    key = [r for _, r in sorted(key_rows["model"])] + ["\\midrule"] + [r for _, r in sorted(key_rows["ablation"])]
    write(out_dir, "comparisons_key", rf"""\begin{{table}}[t]
\caption{{Key differences in weed AP50, mean over 3 seeds (all: \cref{{tab:comparisons}}). Top: RT-DETR-l minus YOLO11s. Bottom: setting minus the same model's baseline (or HSV strong). $p$-values as in \cref{{sec:stats}}.}}
\label{{tab:comparisons-key}}
\centering\setlength{{\tabcolsep}}{{3pt}}
\resizebox{{\columnwidth}}{{!}}{{%
\begin{{tabular}}{{lccccc}}
\toprule
 & \multicolumn{{3}}{{c}}{{Field AP50}} & \multicolumn{{2}}{{c}}{{Gap}} \\
\cmidrule(lr){{2-4}}\cmidrule(lr){{5-6}}
Comparison & $\Delta$ & $p_\mathrm{{img}}$ & $p_\mathrm{{seed}}$ & $\Delta$ & $p_\mathrm{{seed}}$ \\
\midrule
{chr(10).join(key)}
\bottomrule
\end{{tabular}}}}
\end{{table}}
""")


def table_errors(errors, epochs, out_dir, target="field_test"):
    e = errors[(errors["epochs"] == epochs) & (errors["imgsz"] == 640) & (errors["hsv"] == "default")
               & (errors["target"] == target)]
    per_seed = e.pivot_table(index=["model", "seed"], columns="type", values="count", aggfunc="sum", fill_value=0)
    mean = per_seed.groupby("model").mean()
    cols = [("tp", "TP"), ("background", "Backgr."), ("class", "Class"), ("localisation", "Loc."),
            ("duplicate", "Dup."), ("missed", "Missed")]
    rows = []
    for model, label in MODELS.items():
        if model not in mean.index:
            continue
        r = mean.loc[model]
        n_det = sum(r.get(k, 0) for k in ("tp", "duplicate", "class", "localisation", "background", "other"))
        cells = [f"{r.get(k, 0):.0f}" for k, _ in cols]
        rows.append(f"{label} & " + " & ".join(cells) + f" & {r['tp'] / n_det:.2f} & {r['tp'] / r['gt_total']:.2f} \\\\")
    header = " & ".join(h for _, h in cols)
    write(out_dir, "errors", rf"""\begin{{table}}[t]
\caption{{Field test errors of the baselines (both classes, confidence $\geq 0.25$, mean over 3 seeds); types as in \cref{{sec:stats}}. Missed: no detection with $\mathrm{{IoU}} \ge 0.1$.}}
\label{{tab:errors}}
\centering\setlength{{\tabcolsep}}{{3pt}}
\resizebox{{\columnwidth}}{{!}}{{%
\begin{{tabular}}{{l{"r" * (len(cols) + 2)}}}
\toprule
Model & {header} & P & R \\
\midrule
{chr(10).join(rows)}
\bottomrule
\end{{tabular}}}}
\end{{table}}
""")


def table_audit(audit, out_dir):
    a = audit.set_index(["model", "answer"])
    answers = [("unlabelled weed", "Unlabelled weed"), ("unlabelled crop plant", "Unlabelled crop"),
               ("real background", "Real background"), ("unsure", "Unsure")]
    models = [m for m in MODELS if m in a.index.get_level_values(0)]
    rows = []
    for key, label in answers:
        cells = [f"{a.loc[(m, key), 'share']:.2f} [{a.loc[(m, key), 'ci_low']:.2f}, {a.loc[(m, key), 'ci_high']:.2f}]"
                 for m in models]
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    n = " & ".join(f"{int(a.loc[(m, answers[0][0]), 'n'])} of {int(a.loc[(m, answers[0][0]), 'n_background_total'])}"
                   for m in models)
    write(out_dir, "audit", rf"""\begin{{table}}[t]
\caption{{Blind manual audit of random field ``background'' false positives (confidence $\geq 0.25$, seed-0 baselines): share per answer with 95\% Wilson interval.}}
\label{{tab:audit}}
\centering\small
\begin{{tabular}}{{l{"c" * len(models)}}}
\toprule
 & {" & ".join(MODELS[m] for m in models)} \\
\midrule
{chr(10).join(rows)}
\midrule
Audited & {n} \\
\bottomrule
\end{{tabular}}
\end{{table}}
""")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results-dir", type=Path, default=REPO / "results")
    ap.add_argument("--out-dir", type=Path, default=REPO / "report/tables")
    ap.add_argument("--epochs", type=int, default=100)
    args = ap.parse_args()

    table_data(args.results_dir, args.out_dir)
    table_main(pd.read_csv(args.results_dir / "config_summary.csv"), args.epochs, args.out_dir)
    table_comparisons(pd.read_csv(args.results_dir / "comparisons.csv"), args.epochs, args.out_dir)
    table_errors(pd.read_csv(args.results_dir / "errors_per_run.csv"), args.epochs, args.out_dir)
    if (args.results_dir / "label_audit/summary.csv").exists():
        table_audit(pd.read_csv(args.results_dir / "label_audit/summary.csv"), args.out_dir)


if __name__ == "__main__":
    main()
